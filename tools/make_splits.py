"""Generate configs/splits.yaml (deterministic; commit the output, don't hand-edit).

    PYTHONPATH=code python tools/make_splits.py

- tune.epic: 20 EPIC-100 *train* videos whose durations match the 20 quantiles of the
  138 manifest (val) durations, nearest first, ties by id. Never val videos.
- tune.fpvsum_folds: 5 folds over the 49 manifest FPVSum videos, round-robin within
  each category so every fold mixes categories.
- report: the manifest's 138 EPIC + 49 FPVSum videos.
"""

import csv
import re
from pathlib import Path

import yaml

from rewind_eval.gt_epic import load_video_durations

ROOT = Path(__file__).resolve().parents[1]
ANN = ROOT / "data" / "annotations" / "epic"
MANIFEST = ROOT / "kit" / "manifest.csv"
N_TUNE_EPIC = 20
N_FOLDS = 5


def pick_tune_epic(val_durations: list[float], train_durations: dict[str, float]) -> list[str]:
    val = sorted(val_durations)
    targets = [
        val[min(len(val) - 1, int((i + 0.5) * len(val) / N_TUNE_EPIC))] for i in range(N_TUNE_EPIC)
    ]
    chosen: list[str] = []
    for target in targets:
        best = min(
            (vid for vid in train_durations if vid not in chosen),
            key=lambda v: (abs(train_durations[v] - target), v),
        )
        chosen.append(best)
    return sorted(chosen)


def source_video(vid: str) -> str:
    """Clips cut from one YouTube video share a source: BikePolo_DHbYfmjX3WQ_1 → …_3."""
    return re.sub(r"_\d+$", "", vid)


def fpvsum_folds(ids: list[str]) -> dict[str, int]:
    """Round-robin over source videos within each category; clips of one source share
    a fold, so CV never trains and tests on the same footage."""
    by_cat: dict[str, dict[str, list[str]]] = {}
    for vid in sorted(ids):
        by_cat.setdefault(vid.split("_")[0], {}).setdefault(source_video(vid), []).append(vid)
    folds, k = {}, 0
    for cat in sorted(by_cat):
        for src in sorted(by_cat[cat]):
            for vid in by_cat[cat][src]:
                folds[vid] = k % N_FOLDS
            k += 1
    return folds


def main() -> None:
    with open(MANIFEST, encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    epic = [r for r in rows if r["dataset"] == "epic_kitchens_100"]
    fpv = [r["video_id"] for r in rows if r["dataset"] == "fpvsum"]
    with open(ANN / "EPIC_100_train.csv", encoding="utf-8", newline="") as f:
        train_ids = {r["video_id"] for r in csv.DictReader(f)}
    durations = load_video_durations(ANN / "EPIC_100_video_info.csv")
    train_durations = {v: d for v, d in durations.items() if v in train_ids}

    splits = {
        "tune": {
            "epic": pick_tune_epic([float(r["duration_sec"]) for r in epic], train_durations),
            "fpvsum_folds": fpvsum_folds(fpv),
        },
        "report": {"epic": sorted(r["video_id"] for r in epic), "fpvsum": sorted(fpv)},
    }
    header = "# Generated by tools/make_splits.py. Do not edit by hand; rerun the tool.\n"
    out = ROOT / "configs" / "splits.yaml"
    out.write_text(header + yaml.safe_dump(splits, sort_keys=True), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
